messages_file = Path('app/messages_365.csv')

updated_rows = []
updated_dates = set()

with messages_file.open(encoding='utf-8') as f:
    reader = csv.reader(f)
    header = next(reader)
    updated_rows.append(header)
    for row in reader:
        day_index, date_str, msg_type, text = row
        if date_str in new_messages:
            new_type, new_text = new_messages[date_str]
            updated_rows.append([day_index, date_str, new_type, new_text])
            updated_dates.add(date_str)
        else:
            updated_rows.append(row)

with messages_file.open('w', encoding='utf-8', newline='') as f:
    writer = csv.writer(f)
    writer.writerows(updated_rows)

print(f"CSV updated: {len(updated_dates)} rows changed.")
for d in sorted(updated_dates):
    print(f"  {d}")
